'''promptkit 核心：可组合的步骤式工作流。

典型用法（`from promptkit.core import *` 之后这些名字都可用）：

    Input = Function(args=("job",)).Do(
        Prompt(role="user", content="面试一个{{job}}岗位。"),
    )

    wf = Workflow()
    wf.add(
        NewVar("state"),
        Number("count"),          # 指定类型的变量：Number / Str
        Set("count", Read("请输入数量：")),   # "12" 自动变成 12
        While(Var("state") != "结束", max_iterations=20).Do(
            Set("state", "结束"),
        ),
    )
    ctx = wf.run(agent=agent)
'''
